import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

// Keep the originals (including social preview URLs) intact. Only UI assets
// use these content-addressed derivatives, so a changed source gets a new URL.
const images = {
  art1: "art-1.jpg",
  art2: "art-2.jpg",
  art3: "art-3.jpg",
  art4: "art-4.jpg",
  art5: "art-5.jpg",
  art6: "art-6.jpg",
  creator1: "artist.png",
  creator2: "creator-2.jpg",
  creator3: "creator-3.jpg",
  heroInterior: "hero-interior.jpg",
  heroStudio: "hero-studio.jpg",
  roomDining: "room-dining.jpg",
};
const widths = [320, 480, 640, 960, 1280, 1920];
const directory = path.resolve("public/images/optimized");
await mkdir(directory, { recursive: true });
const urls = {};
const sizes = [];
// Sequential processing bounds memory on small build machines.
for (const [key, filename] of Object.entries(images)) {
  const source = await readFile(path.resolve("src/assets", filename));
  const hash = createHash("sha256").update(source).digest("hex").slice(0, 12);
  const stem = `${path.parse(filename).name}-${hash}`;
  let largest;
  for (const width of widths) {
    const output = await sharp(source)
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 82, effort: 5 })
      .toBuffer();
    await writeFile(path.join(directory, `${stem}-${width}.webp`), output);
    if (width === 1280) largest = output.length;
  }
  urls[key] = `/images/optimized/${stem}-1280.webp`;
  sizes.push({ image: filename, originalBytes: source.length, webp1280Bytes: largest });
}
await writeFile(
  path.resolve("src/lib/static-images.generated.ts"),
  `// Generated by npm run images:optimize. Do not edit by hand.\nexport const IMAGES = ${JSON.stringify(urls, null, 2)} as const;\n`,
);
console.log(JSON.stringify(sizes, null, 2));
